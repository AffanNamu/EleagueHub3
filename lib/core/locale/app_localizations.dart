  String tr(String key) {
    final lang = locale.languageCode;
    final current = _strings[lang];
    if (current != null && current.containsKey(key)) {
      return current[key]!;
    }
    final en = _strings['en'];
    if (en != null && en.containsKey(key)) {
      return en[key]!;
    }
    return key;
  }

