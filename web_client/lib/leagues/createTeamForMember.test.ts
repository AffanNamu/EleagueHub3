// web_client/lib/leagues/createTeamForMember.test.ts
//
// No test runner configured in this app (see sessionOptions.test.ts) --
// same dependency-free convention: `npx tsx lib/leagues/createTeamForMember.test.ts`.
//
// Covers the Phase B follow-up fix: the web "Already Joined -> Add" flow
// (admin/teams/page.tsx's addResolvedAsTeam, now backed by
// createTeamForMemberWeb) must create the team AND sync
// membership.teamId in the same operation, never silently reassign an
// already-differently-assigned member, and never double-process a
// member already on the target team.

import { planCreateTeamForMember } from './createTeamForMemberPlan';

let failures = 0;

function assertEqual<T>(actual: T, expected: T, label: string) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) {
    failures++;
    console.error(`FAIL: ${label}\n  expected: ${JSON.stringify(expected)}\n  actual:   ${JSON.stringify(actual)}`);
  } else {
    console.log(`ok - ${label}`);
  }
}

const baseFields = { name: 'Al Haram', ownerId: 'uid_alharam', teamImageUrl: '' };

// 1. Joined + teamless member -> team created, membership.teamId points to it.
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_alharam',
    membershipExists: true,
    currentTeamId: '',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.outcome, 'assign', '1a. teamless joined member -> outcome is assign');
  assertEqual(plan.teamWrite?.id, 'uid_alharam', '1b. team write targets the member\'s own uid as team id');
  assertEqual(plan.membershipWrite?.data.teamId, 'uid_alharam', '1c. membership write sets teamId to the new team');
}

// 2. Existing membership identity is never touched/regenerated by this
// plan: for an existing membership it's an 'update' that writes ONLY
// teamId/updatedAtMs -- no id/userId/role field is ever included, so the
// membership's own identity (its doc id, set by the caller's ref, and
// its userId/role fields) can never be altered by this operation.
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_alharam',
    membershipExists: true,
    currentTeamId: '',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.membershipWrite?.mode, 'update', '2a. existing membership -> update, not a fresh create');
  assertEqual(
    Object.keys(plan.membershipWrite?.data ?? {}).sort(),
    ['teamId', 'updatedAtMs'],
    '2b. update touches only teamId/updatedAtMs -- identity fields untouched',
  );
}

// 3. No membership doc yet (edge case) -> plan creates exactly one new
// membership (role: member), never a duplicate -- same shape as an
// existing membership's update, just with mode: 'create'.
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_newjoin',
    membershipExists: false,
    currentTeamId: '',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.membershipWrite?.mode, 'create', '3. no prior membership -> plan creates exactly one');
  assertEqual(plan.membershipWrite?.data.role, 1, '3b. created membership is role: member, not organizer');
}

// 4. No duplicate team: the team write always targets the SAME doc id
// (the member's own uid) regardless of whether this is the member's
// first "Add" or a repeat -- Firestore merge-set on that fixed id can
// never produce two team docs for the same member.
{
  const first = planCreateTeamForMember({
    leagueId: 'league1', teamId: 'uid_alharam', membershipExists: true, currentTeamId: '', now: 1000, teamFields: baseFields,
  });
  const second = planCreateTeamForMember({
    leagueId: 'league1', teamId: 'uid_alharam', membershipExists: true, currentTeamId: 'uid_alharam', now: 2000, teamFields: baseFields,
  });
  assertEqual(first.teamWrite?.id, second.teamWrite?.id, '4. repeat plan targets the identical team doc id');
}

// 5. Existing assigned member (already on a DIFFERENT team) is never
// incorrectly processed: no team write, no membership write -- the
// caller throws instead of applying anything.
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_alharam',
    membershipExists: true,
    currentTeamId: 'team_some_other_team',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.outcome, 'blockedAlreadyOnDifferentTeam', '5a. already on a different team -> blocked');
  assertEqual(plan.teamWrite, null, '5b. blocked outcome -> no team write planned');
  assertEqual(plan.membershipWrite, null, '5c. blocked outcome -> no membership write planned');
}

// Idempotent repeat: a member already on the exact team being "added"
// again is a no-op, not an error and not a double-write of the
// membership (the team write still refreshes harmlessly via merge, but
// no membership write is planned at all).
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_alharam',
    membershipExists: true,
    currentTeamId: 'uid_alharam',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.outcome, 'noopAlreadyOnTeam', '6a. already on the target team -> idempotent no-op');
  assertEqual(plan.membershipWrite, null, '6b. no-op -> no membership write planned (no duplicate possible)');
}

// 10 (orphan-state proxy): the blocked outcome never returns a partial
// plan -- teamWrite and membershipWrite are null together, never one
// without the other, so a caller that checks teamWrite === null before
// doing any tx.set can never apply only half the change.
{
  const plan = planCreateTeamForMember({
    leagueId: 'league1',
    teamId: 'uid_alharam',
    membershipExists: true,
    currentTeamId: 'team_some_other_team',
    now: 1000,
    teamFields: baseFields,
  });
  assertEqual(plan.teamWrite === null && plan.membershipWrite === null, true, '10. blocked plan is all-or-nothing (both null together)');
}

if (failures > 0) {
  console.error(`\n${failures} assertion(s) failed.`);
  process.exit(1);
} else {
  console.log('\nAll createTeamForMember assertions passed.');
}
